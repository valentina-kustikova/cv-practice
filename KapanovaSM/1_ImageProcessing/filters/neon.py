import numpy as np
from .base import ImageFilter
from .grayscale import ToGray


class Neon(ImageFilter): 
    # Неоновый эффект: контур + свечение вокруг. Без затемнения базы. С настраиваемой толщиной контура.
    def __init__(self, neon_gain=40, neon_brightness=0.8,
                 color=(255, 10, 149), neon_brightness_width=10,
                 edge_thickness=1):
        self.neon_gain = neon_gain   # порог градиента (насколько резким должен быть перепад, чтобы стать контуром).
        self.neon_brightness = neon_brightness         # яркость свечения (множитель для слоя ореола)
        self.color = color         # цвет неона в формате (B, G, R)
        self.neon_brightness_width = neon_brightness_width         # ширина ореола (влияет на то, как далеко расходится свечение)
        self.edge_thickness = max(int(edge_thickness), 0)  # толщина самого контура в пикселях (>=0). 1 — как в оригинале (одна дилатация) защита от отрицательных значений

    @staticmethod
    def _dilate(mask):
        # Дилатация (расширение) маски по кресту (4 соседа: верх, низ, лево, право).
        # Каждый вызов делает контур толще с каждой стороны на 1 пиксель. 
        out = mask.copy()  # Копируем маску, чтобы не изменить оригинал.
        # Сдвигаем маску вверх, вниз, влево и вправо на 1 пикс, и берем максимум из соседей.
        # Если хотя бы один сосед белый (1.0), текущий пиксель тоже станет белым.
        out[1:, :] = np.maximum(out[1:, :], mask[:-1, :])   # тянем вверх
        out[:-1, :] = np.maximum(out[:-1, :], mask[1:, :])  # тянем вниз
        out[:, 1:] = np.maximum(out[:, 1:], mask[:, :-1])   # тянем влево
        out[:, :-1] = np.maximum(out[:, :-1], mask[:, 1:])  # тянем вправо
        return out

    def _neon_brightness_by_dilation(self, mask, sigma): # Создание ореола свечения
        
        neon_brightness = mask * 0.4 # начальная яркость свечения (базовый минимум)
        current = mask # В цикле на каждом шаге current раздуваем на 1 пикс, и перезаписываем 
        radius = max(1, int(sigma * 3)) # сколько раз будем расширять (сигма «ширина» в смысле «степень размытости»)
        # neon_brightness_width = sigma If 10 свечение растягивается на 3 * 10 = 30 пикселей, 
        # но визуально ты его видишь в основном в первых 10-15 пикселях, потому что дальше оно уже слишком тусклое из-за гаусса
        
        for r in range(1, radius + 1):
            current = self._dilate(current) # расширяем контур на 1 шаг
            
            # Ф-ла гауссова затухания дает максимальную яркость у контура и плавно уменьшает её к краям.
            # вычисляет, насколько ярким должен быть пиксель на расстоянии r от контура (всего). не от одной точки
            # Формула Гаусса - график колокол:
            # Плоская вершина: прямо у контура яркость почти не падает, линия выглядит плотной.
            # Быстрый спад
            # Длинный хвост: свечение не обрывается резко
            weight = np.exp(-(r * r) / (2 * sigma * sigma)) * 0.4
            
            # np.maximum нужен, чтобы слои не складывались в белый пересвет, а брали самый яркий пиксель из всех шагов.
            # Он смотрит на все слои, которые накрыли этот пиксель на всех шагах, и оставляет только самый яркий.
            # чтобы это не было просто толстым белым пятном, мы каждый шаг расширения умножаем на "вес" (гауссово затухание). Чем дальше от контура, тем тусклее.
            neon_brightness = np.maximum(neon_brightness, current * weight)
            
        return neon_brightness

    def apply_filter(self, image):
        img = image.astype(np.float32)  # 1. Переводим картинку в дробный формат (float32), чтобы не терять точность при вычислениях

        # 2. Делаем серую копию картинки с пом фильтра ToGray
        gray = ToGray().apply_filter(img).astype(np.float32)

        # 3. Вычисляем градиент (перепады яркости). 
        # Используем центральные разности: разница между правым и левым соседом (gx), 
        # и между нижним и верхним (gy). Это позволяет найти границы объектов.
        
        # Создает две пустые таблицы (gx и gy) такого же размера, как картинка (gray), и заполняет их нулями.
        # будем записывать в них результаты вычислений (разницу между соседями по горизонтали и вертикали).
        gx = np.zeros_like(gray)
        gy = np.zeros_like(gray)
        gx[:, 1:-1] = gray[:, 2:] - gray[:, :-2]
        gy[1:-1, :] = gray[2:, :] - gray[:-2, :]
        
        # теперь для каждого пикселя: gx (насколько сильно меняется яркость влево-вправо) и gy (насколько сильно меняется вверх-вниз).
        # Длина вектора градиента (теорема Пифагора) — показывает силу перепада в каждой точке
        mag = np.sqrt(gx * gx + gy * gy)
        
        # 4. Создаем маску контура. Если перепад яркости больше neon_gain — ставим 1 (белый) - реально контур, иначе 0 (черный)
        mask = (mag > self.neon_gain).astype(np.float32)

        # 5. Утолщаем контур. а именно расширяем маску. Повторяем дилатацию столько раз, сколько указано в edge_thickness.
        for _ in range(self.edge_thickness):
            mask = self._dilate(mask)

        # 6. Создаем слой свечения (ореол)
        sigma = max(1.0, float(self.neon_brightness_width))
        neon_brightness_mask = self._neon_brightness_by_dilation(mask, sigma)

        # 7. Формируем итоговое изображение
        cb, cg, cr = self.color
        base = img  # оригинал

        # Слой самого контура (четкие линии) mask — это наша черно-белая маска (где 1.0 — это контур, а 0.0 — фон).
        # как трафарет: Где mask = 0 пикс остается черным. Где mask = 1.0 (контур) пиксель красится цветом.
        edges = np.zeros_like(img)
        edges[:, :, 0] = mask * cb
        edges[:, :, 1] = mask * cg
        edges[:, :, 2] = mask * cr

        # Слой свечения (мягкий ореол)
        neon_brightness_layer = np.zeros_like(img) # черный холст размера картинки. Нам нужен отдельный слой, чтобы потом наложить на него ореол.
        # Закрашиваем этот холст цветом неона с помощью маски свечения (neon_brightness_mask).
        # поэтому цвет будет плавно затухать от контура к краям.
        neon_brightness_layer[:, :, 0] = neon_brightness_mask * cb  # Синий канал
        neon_brightness_layer[:, :, 1] = neon_brightness_mask * cg  # Зеленый канал
        neon_brightness_layer[:, :, 2] = neon_brightness_mask * cr  # Красный канал

        # Складываем: оригинал + контур + свечение (умноженное на яркость).
        out = base + edges + neon_brightness_layer * self.neon_brightness
        
        return np.clip(out, 0, 255).astype(np.uint8) # np.clip не дает значениям выйти за пределы 0..255, astype переводит обратно в целые числа (uint8)
