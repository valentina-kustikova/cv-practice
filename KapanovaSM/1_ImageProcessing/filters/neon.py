# Неоновый эффект: контур + свечение вокруг

import numpy as np
from .base import ImageFilter

def _sobel(gray):
    # Оператор Собеля - распознает границы на серых картинках
    # дополняем картинку по 1 пикселю с каждой стороны, копируя края тк Sobel использует окно 3×3. Без padding крайние пиксели не имели бы соседей — формула не работает.
    g = np.pad(gray, 1, mode='edge')
    
    # свёртка с ядром Gx = [[-1,0,1],[-2,0,2],[-1,0,1]] — производная по X. изменение яркости по X — вертикальные границы дают большое gx
    gx = (-1 * g[:-2, :-2] + 1 * g[:-2, 2:]
          - 2 * g[1:-1, :-2] + 2 * g[1:-1, 2:]
          - 1 * g[2:, :-2] + 1 * g[2:, 2:])
   
    # Ядро Gy = [[-1,-2,-1],[0,0,0],[1,2,1]] — производная по Y
    gy = (-1 * g[:-2, :-2] - 2 * g[:-2, 1:-1] - 1 * g[:-2, 2:]
          + 1 * g[2:, :-2] + 2 * g[2:, 1:-1] + 1 * g[2:, 2:])

    # объединяет два направления в одно число — общую силу границы. итог: magnitude — матрица силы границ
    return np.sqrt(gx ** 2 + gy ** 2)


def _box_blur_cumsum(image, radius): 
    # Box-размытие через np.cumsum 
    # Размывает изображение — усредняет каждый пиксель с соседями в окне
    # Используется для создания мягкого свечения вокруг контура
    
    # Если радиус меньше 1 — размытие не нужно (нет окна). Возвращаем оригинал.
    # self.blur_size = radius
    if radius < 1:
        return image

    def blur_axis(img, axis): # Размытие вдоль одной оси
        '''np.pad добавляет рамку вокруг картинки, чтобы у крайних пикселей тоже были соседи для усреднения. 
        Сколько добавлять — задаёт pad: сначала 0 со всех сторон, потом только по нужной оси ставим radius 
        (потому что размываем сначала по вертикали, потом по горизонтали). 
        [(0, 0), (0, 0)]:
        Строки: 0 сверху, 0 снизу — ничего не добавляем.
        Столбцы: 0 слева, 0 справа — ничего не добавляем.'''
        pad = [(0, 0), (0, 0)]
        pad[axis] = (radius, radius) # замен текущее значение на новое
        padded = np.pad(img, pad, mode='edge') # mode='edge' «копировать крайние пиксели»
        
        # накопленная сумма для быстрого получения суммы окна. Она считает сумму всех элементов до текущего включительно.
        cumsum = np.cumsum(padded, axis=axis)

        # Разность двух cumsum = сумма элементов в окне = сумма значений всех пикселей внутри  квадратика.
        # Делим на размер окна = (2*radius + 1) — получаем среднее
        if axis == 0: # вертикаль (строки)
            '''[2*radius:, :] — срез: берём элементы начиная с индекса 2*radius и до конца, все столбцы. это правые границы окон для каждого пикселя.
            [:-2*radius, :] - левые границы окон для каждого пикселя'''
            return (cumsum[2 * radius:, :] - cumsum[:-2 * radius, :]) / (2 * radius + 1)
        else:
            return (cumsum[:, 2 * radius:] - cumsum[:, :-2 * radius]) / (2 * radius + 1)
        # вернет матрицу ту же, что на входе, но в кажд пикс усреднённ с соседями вдоль одной оси.


    # Три прохода по каждой оси размытие (более плавное)
    out = image.astype(np.float32)
    for _ in range(3):
        out = blur_axis(out, axis=0)   # размытие по вертикали
        out = blur_axis(out, axis=1)   # размытие по горизонтали
    return out # размытая картинка по обеим осям


class Neon(ImageFilter):
    # Неон: контур + свечение вокруг

    def __init__(self, strength: float = 1.5,
                 blur_size: float = 5.0):
        # strength — яркость неона (>= 0)
        # blur_size — ширина свечения (>0)
        if strength < 0:
            raise ValueError('strength должен быть >= 0')
        if blur_size < 0:
            raise ValueError('blur_size должен быть >= 0')
        self.strength = strength
        self.blur_size = max(int(blur_size), 1)

    def apply_filter(self, image):

        # 1. Приведение к 3-канальному если надо
        orig_rgb = image[..., :3].astype(np.float32)

        # 2. Серое по формуле 
        # Y = 0.299·R + 0.587·G + 0.114·B
        gray = (0.299 * orig_rgb[..., 2]
                + 0.587 * orig_rgb[..., 1]
                + 0.114 * orig_rgb[..., 0])

        # 3. Sobel 
        mag = _sobel(gray)
        mag = mag / max(float(mag.max()), 1.0) # 4. Нормализация в 0..1 — делим на максимум Теперь значения в диапазоне [0, 1]

        # 5. Усиление — умножаем на strength, чтобы контуры были ярче
        mag = mag * self.strength
        edges = np.clip(mag, 0.0, 1.0) # 6. Обрезаем в 0..1 — получаем маску контуров

        # 7. Два слоя свечения через box blur 
        #    Узкое (blur_size) и широкое (blur_size * 2) — для плавного затухания
        soft_glow = _box_blur_cumsum(edges, self.blur_size)
        wide_glow = _box_blur_cumsum(edges, self.blur_size * 2)

        # 8. Итоговая маска: контур + узкое свечение + широкое свечение
        #    edges × 1.0 — сам контур (ярче всего) soft_glow × 0.8 — близкое свечение wide_glow × 0.5 — далёкое свечение
        # матрица, в каждой ячейке число 0-1. итоговая матрица яркости неона. Она определяет, насколько яркий неон будет в этой точке.
        # Что даёт: в точке контура — все три слоя яркие → сумма большая. Чуть в стороне — только soft_glow + wide_glow → меньше. Далеко — только wide_glow → ещё меньше. В гладкой области — 0.
        neon_mask = (edges * 1.0
                     + soft_glow * 0.8
                     + wide_glow * 0.5)
        neon_mask = np.clip(neon_mask, 0.0, 1.0)[..., None] # Обрезаем до [0, 1] и добавляем ось для broadcasting (h, w, 1)

        base = orig_rgb.copy() # 9. копия, чтобы не менять исходник

        # 10. Бирюзовый неоновый слой
        #     B=255, G=255, R=50 → бирюзовый (B + G = cyan)
        #     Каждый канал умножается на neon_mask (0..1) — где нет контура, там 0
        neon_layer = np.concatenate([
            neon_mask * 255,   # синий канал
            neon_mask * 255,   # зелёный канал
            neon_mask * 50,   # красный канал (ослаблен)
        ], axis=-1) 
        # np.concatenate([B, G, R], axis=-1) — склеивает три матрицы в одну (h, w, 3). axis=-1 — по последней оси — по каналам.
        # три отдельные матрицы B, G, R — склеиваются в одну трёхканальную.
      

        # 11. Наложение на оригинал
        result = base + neon_layer
        result = np.clip(result, 0, 255).astype(np.uint8) # обрезает значения до допустимых и превращает в целые числа

        return result