import numpy as np
from .base import ImageFilter


class Film(ImageFilter): # Имитация инфракрасной плёнки
    # красный сдвиг каналов + зерно

    def __init__(self, strength=0.7, noise_sigma=8.0):
        if not 0 <= strength <= 1:
            raise ValueError('strength должен быть в [0, 1]')
        self.strength = strength
        self.noise_sigma = noise_sigma

    def apply_filter(self, image):
        img = image.astype(np.float32)
        s = self.strength

        # Обработка серой картинки
        # Film работает с тремя каналами. Если img — серая (2D), то img[:, :, 0] вызовет ошибку — третьей оси не существует.
        # Решение: превратить 2D в 3D — скопировать единственный канал три раза.
        if img.ndim == 2:
            img = np.stack([img] * 3, axis=2)

        # Разделяем каналы BGR
        b = img[:, :, 0] # берём нулевой канал
        g = img[:, :, 1]
        r = img[:, :, 2]

        # Насыщенный красный: R растёт сильно, G и B падают
        new_r = r * (1 + 0.6 * s)      # R сильно усиливается
        new_g = g * (1 - 0.4 * s)      # G падает
        new_b = b * (1 - 0.7 * s)      # B сильно падает

        img = np.stack([new_b, new_g, new_r], axis=2) #собирает три канала обратно в картинку. три матрицы (h, w) становятся одной картинкой (h, w, 3).
        # np.stack — складывает массивы вдоль новой оси. [new_b, new_g, new_r] — список из трёх каналов. axis=2 — складываем по третьей оси.

        # гауссов шум
        if self.noise_sigma > 0:
            noise = np.random.normal(0, self.noise_sigma, img.shape)
            # np.random.normal — генератор случайных чисел из нормального (гауссова) распределения.
            # Среднее = 0. Значит, случайные числа будут примерно поровну положительные и отрицательные — вокруг нуля
            # чем больше self.noise, тем сильнее разброс — тем заметнее зерно.
            # генерируется массив такой же формы, как картинка — для каждого пикселя каждого канала будет своё случайное число.
            # Итог: массив noise, заполненный случайными числами:

            img = img + noise # Прибавляем шум к каждому пикселю => зернистость
            # Каждый пиксель каждого канала получает своё случайное число. один и тот же пиксель изменяется по-разному в разных каналах.

        return np.clip(img, 0, 255).astype(np.uint8)